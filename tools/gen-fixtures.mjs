#!/usr/bin/env node
/* Generate the derived artefacts of the test-data pool:
 *
 *   build/xlsx/<group>/<name>.xlsx      a survey workbook per case
 *   src/ui/presets.generated.js         the page's built-in examples (ES module)
 *
 *   node tools/gen-fixtures.mjs            # everything (then: node tools/build-page.mjs)
 *   node tools/gen-fixtures.mjs --check    # exit 1 if presets.generated.js is stale
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { listCases, loadCase, ROOT } from "./lib/cases.mjs";
import { writeWorkbook } from "../src/io/xlsx.js";
import { FIELDS } from "../src/io/csv.js";
import { HOW_TO_LINES } from "./lib/howto.mjs";

export const GENERATED = path.join(ROOT, "src", "ui", "presets.generated.js");

/** ES module source for the presets, from the cases flagged with a preset key. */
export function presetsSource(cases) {
  const js = v => JSON.stringify(v ?? "");
  const out = [];
  out.push(`/* ------------------------------------------------ presets — GENERATED by tools/gen-fixtures.mjs from testdata/, do not edit */`);
  out.push(`function R(id,type,desc,rating,voltage,from,notes,prot){ return {id,type,desc,rating,voltage,from,notes,prot:prot||""}; }`);
  out.push(`const PRESETS={`);
  const presets = cases.filter(c => c.data.preset).sort((a, b) => Number(a.data.preset) - Number(b.data.preset));
  for (const c of presets) {
    const i = c.data.info || {};
    out.push(`  ${js(String(c.data.preset))}:{ /* ${c.data.group}/${c.data.name} */`);
    out.push(`    info:{site:${js(i.site)},date:${js(i.date)},by:${js(i.by)},notes:${js(i.notes)}},`);
    out.push(`    rows:[`);
    for (const r of c.rows)
      out.push(`      R(${[r.id, r.type, r.desc, r.rating, r.voltage, r.from, r.notes, r.prot].map(js).join(",")}),`);
    out.push(`    ]},`);
  }
  out.push(`};`);
  out.push(``);
  out.push(`export { R, PRESETS };`);
  return out.join("\n") + "\n";
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const check = process.argv.includes("--check");
  const cases = listCases().map(loadCase);
  const src = presetsSource(cases);
  const have = fs.existsSync(GENERATED) ? fs.readFileSync(GENERATED, "utf8") : "";

  if (check) {
    if (have !== src) { console.error("src/ui/presets.generated.js is stale — run: node tools/gen-fixtures.mjs"); process.exit(1); }
    console.log("presets up to date");
  } else {
    fs.mkdirSync(path.dirname(GENERATED), { recursive: true });
    if (have !== src) fs.writeFileSync(GENERATED, src);
    console.log(`${path.relative(ROOT, GENERATED)} ${have !== src ? "written" : "unchanged"}`);
    let n = 0;
    for (const c of cases) {
      const dir = path.join(ROOT, "build", "xlsx", c.data.group);
      fs.mkdirSync(dir, { recursive: true });
      const rows = c.rows.map(r => Object.fromEntries(FIELDS.map(f => [f, r[f] ?? ""])));
      fs.writeFileSync(path.join(dir, `${c.data.name}.xlsx`), writeWorkbook({ info: c.data.info || {}, rows, howTo: HOW_TO_LINES }));
      n++;
    }
    console.log(`${n} workbook(s) written under build/xlsx/`);
  }
}
