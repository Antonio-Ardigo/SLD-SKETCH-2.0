#!/usr/bin/env node
/* Generate the derived artefacts of the test-data pool:
 *
 *   build/xlsx/<group>/<name>.xlsx      a survey workbook per case
 *   src/ui/presets.generated.js         the sketchpad's built-in examples
 *   sld_sketchpad.html                  presets block replaced in place
 *
 *   node tools/gen-fixtures.mjs            # everything
 *   node tools/gen-fixtures.mjs --check    # exit 1 if the page's presets block is stale
 */
import fs from "node:fs";
import path from "node:path";
import { listCases, loadCase, ROOT } from "./lib/cases.mjs";
import { writeWorkbook } from "./lib/xlsx.mjs";
import { HOW_TO_LINES } from "./lib/howto.mjs";
import { FIELDS } from "./lib/csv.mjs";

const PAGE = path.join(ROOT, "sld_sketchpad.html");
const GENERATED = path.join(ROOT, "src", "ui", "presets.generated.js");
const START = "/* ------------------------------------------------ presets";
const END = "/* ------------------------------------------------ UI wiring */";

const check = process.argv.includes("--check");

/** JS source for the presets block, from the cases flagged with a preset key. */
export function presetsSource(cases) {
  const js = v => JSON.stringify(v ?? "");
  const out = [];
  out.push(`${START} — GENERATED by tools/gen-fixtures.mjs from testdata/, do not edit */`);
  out.push(`function R(id,type,desc,rating,voltage,from,notes,prot){ return {id,type,desc,rating,voltage,from,notes,prot:prot||""}; }`);
  out.push(`const PRESETS={`);
  const presets = cases.filter(c => c.data.preset).sort((a, b) => Number(a.data.preset) - Number(b.data.preset));
  for (const c of presets) {
    const i = c.data.info || {};
    out.push(`  ${js(String(c.data.preset))}:{ /* ${c.data.group}/${c.data.name} */`);
    out.push(`    info:{site:${js(i.site)},date:${js(i.date)},by:${js(i.by)},notes:${js(i.notes)}},`);
    out.push(`    rows:[`);
    for (const r of c.rows)
      out.push(`      R(${[r.id, r.type, r.desc, r.rating, r.voltage, r.from, r.notes, r.prot].map(js).join(",")}),`);
    out.push(`    ]},`);
  }
  out.push(`};`);
  out.push(``);
  return out.join("\n") + "\n";
}

function spliceIntoPage(block) {
  const html = fs.readFileSync(PAGE, "utf8");
  const a = html.indexOf(START), b = html.indexOf(END);
  if (a < 0 || b < 0 || b < a) throw new Error("presets markers not found in sld_sketchpad.html");
  const current = html.slice(a, b);
  return { html: html.slice(0, a) + block + html.slice(b), stale: current !== block };
}

function main() {
  const cases = listCases().map(loadCase);
  const block = presetsSource(cases);
  const { html, stale } = spliceIntoPage(block);

  if (check) {
    if (stale) { console.error("sld_sketchpad.html presets block is stale — run: node tools/gen-fixtures.mjs"); process.exit(1); }
    console.log("presets block up to date");
    return;
  }

  fs.mkdirSync(path.dirname(GENERATED), { recursive: true });
  fs.writeFileSync(GENERATED, block);
  if (stale) fs.writeFileSync(PAGE, html);
  console.log(`${path.relative(ROOT, GENERATED)} written${stale ? "; sld_sketchpad.html presets updated" : ""}`);

  let n = 0;
  for (const c of cases) {
    const dir = path.join(ROOT, "build", "xlsx", c.data.group);
    fs.mkdirSync(dir, { recursive: true });
    const rows = c.rows.map(r => Object.fromEntries(FIELDS.map(f => [f, r[f] ?? ""])));
    fs.writeFileSync(path.join(dir, `${c.data.name}.xlsx`), writeWorkbook({ info: c.data.info || {}, rows, howTo: HOW_TO_LINES }));
    n++;
  }
  console.log(`${n} workbook(s) written under build/xlsx/`);
}

main();
